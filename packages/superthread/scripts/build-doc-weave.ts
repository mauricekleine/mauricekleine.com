import { join } from "node:path";

const output = join(import.meta.dir, "../items/doc/weave.js");
const bundle = await Bun.build({
  entrypoints: [join(import.meta.dir, "doc-weave.ts")],
  target: "browser",
  format: "iife",
  minify: true,
});
const script = `// generated by bun run doc-weave\n${await bundle.outputs[0]!.text()}`;
if (Bun.argv.includes("--check")) {
  const file = Bun.file(output);
  if (!(await file.exists()) || (await file.text()) !== script) {
    throw new Error("items/doc/weave.js is stale; run bun run --cwd packages/superthread doc-weave");
  }
} else {
  await Bun.write(output, script);
}
