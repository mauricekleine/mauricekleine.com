import { join } from "node:path";

const output = join(import.meta.dir, "../items/doc/notes.js");
const bundle = await Bun.build({
  entrypoints: [join(import.meta.dir, "doc-notes.ts")],
  target: "browser",
  format: "iife",
  minify: true,
});
const script = `// generated by bun run doc-notes\n${await bundle.outputs[0]!.text()}`;
if (Bun.argv.includes("--check")) {
  const file = Bun.file(output);
  if (!(await file.exists()) || (await file.text()) !== script) {
    throw new Error("items/doc/notes.js is stale; run bun run --cwd packages/superthread doc-notes");
  }
} else {
  await Bun.write(output, script);
}
