import { join } from "node:path";

const packageRoot = join(import.meta.dir, "..");
const targets = [
  { input: "scripts/doc-field-art.ts", output: "items/doc/field-art.js", format: "iife" },
  {
    input: "items/lib/field-core.ts",
    output: "../../skills/superthread-visuals/scripts/field.js",
    format: "esm",
  },
] as const;

for (const { input, output, format } of targets) {
  const bundle = await Bun.build({
    entrypoints: [join(packageRoot, input)],
    tsconfig: join(packageRoot, "tsconfig.json"),
    target: "browser",
    format,
    minify: true,
  });
  const source = `// generated by bun run field-bundles\n${await bundle.outputs[0]!.text()}`;
  const path = join(packageRoot, output);
  if (Bun.argv.includes("--check")) {
    const file = Bun.file(path);
    if (!(await file.exists()) || (await file.text()) !== source) {
      throw new Error(`${output} is stale. Run bun run --cwd packages/superthread field-bundles`);
    }
  } else {
    await Bun.write(path, source);
  }
}
